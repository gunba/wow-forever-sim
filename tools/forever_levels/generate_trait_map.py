#!/usr/bin/env python3
"""Map the client's talent trait nodes and entries to the simulator's talent string positions, for the planner's
character message (C_Traits node, entry and rank). Writes sim/planner/traits_generated.go.

    python3 tools/forever_levels/generate_trait_map.py [--build 1.60.1.70374]
"""
import argparse, json, os, pathlib, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools/forever_talents"))
import export_beta  # noqa: E402

OUT = REPO / "sim/planner/traits_generated.go"
CLASSES = ["warrior"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=(REPO / "assets/db_inputs/forever_client_build.txt").read_text().strip())
    a = ap.parse_args()
    cache = str(REPO / "tools/data_watch/.cache")
    client = export_beta.Client(a.build, cache)
    lines = ["// Code generated by tools/forever_levels/generate_trait_map.py. DO NOT EDIT.", f"// Client build {a.build}.", "",
             "package planner", "", "// Trait node entry -> position in the simulator's talent string.",
             "var traitEntries = map[string]map[int32]talentSlot{"]
    for cls in CLASSES:
        sim_trees = json.load(open(REPO / "ui/core/talents/trees" / f"{cls}.json"))
        index = {}
        for ti, tree in enumerate(sim_trees):
            for i, t in enumerate(tree["talents"]):
                index[export_beta.norm(t["name"])] = (ti, i, t["maxPoints"], t["fieldName"])
        sim_names = set(index)
        tree_id = client.class_tree(sim_names)
        lines.append(f'\t"{cls.upper()}": {{')
        n = 0
        for node in client.nodes[tree_id]:
            for entry in client.node_entries.get(node["ID"], []):
                d = client.definition[entry["TraitDefinitionID"]]
                name = d["OverrideName_lang"] or client.spell_name.get(d["SpellID"], "")
                slot = index.get(export_beta.norm(name))
                if not slot:
                    continue
                ti, i, mx, field = slot
                lines.append(f'\t\t{entry["ID"]}: {{Tree: {ti}, Index: {i}, MaxRank: {mx}, Node: {node["ID"]}, Field: "{field}"}},')
                n += 1
        lines.append("\t},")
        print(cls, n, "entries")
    lines += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    gofmt = pathlib.Path.home() / ".local/share/go/bin/gofmt"
    subprocess.run([str(gofmt) if gofmt.exists() else "gofmt", "-w", str(OUT)], check=False)


if __name__ == "__main__":
    main()
