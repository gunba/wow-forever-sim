#!/usr/bin/env python3
"""Per-level player base stats for levels 1-60, written to sim/core/base_stats_levels_generated.go.

    python3 tools/forever_levels/generate_base_stats.py            # from the snapshots in assets/db_inputs/basestats
    python3 tools/forever_levels/generate_base_stats.py --refresh  # re-download the sources first

Sources (snapshots under assets/db_inputs/basestats/):
- player_class_stats.json: base health, mana and Str/Agi/Sta/Int/Spi per class and level, AzerothCore
  data/sql/base/db_world/player_class_stats.sql. Its level-60 rows equal the simulator's level-60 ClassBaseStats.
- player_expected_stat.json: the client's PlayerExpectedStat (crit per Agility per class and level).
- forever_race_starting_stats.json: Forever's rebalanced level-1 race stats, as reported by players.

Player base stats are server data, not client data, so the class curves are Classic/Wrath values; only the level-60
values have been checked against the simulator's benchmark, and the race part is interpolated (see RaceOffsetAtLevel).
"""
import argparse, json, pathlib, re, subprocess, sys, urllib.request

REPO = pathlib.Path(__file__).resolve().parents[2]
DATA = REPO / "assets/db_inputs/basestats"
OUT = REPO / "sim/core/base_stats_levels_generated.go"
AC_URL = "https://raw.githubusercontent.com/azerothcore/azerothcore-wotlk/master/data/sql/base/db_world/player_class_stats.sql"
CLASSES = {1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest", 7: "Shaman", 8: "Mage", 9: "Warlock", 11: "Druid"}


def refresh(build):
    raw = urllib.request.urlopen(urllib.request.Request(AC_URL, headers={"User-Agent": "wow-forever-sim"}), timeout=120).read().decode()
    rows = []
    for m in re.finditer(r"\((\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+)\)", raw):
        c, lvl, hp, mana, st, ag, sta, inte, spi = map(int, m.groups())
        if c in CLASSES and lvl <= 60:
            rows.append(dict(classId=c, level=lvl, health=hp, mana=mana, strength=st, agility=ag, stamina=sta, intellect=inte, spirit=spi))
    (DATA / "player_class_stats.json").write_text(json.dumps({"source": AC_URL, "rows": rows}, indent=0))
    sys.path.insert(0, str(REPO / "tools/data_watch"))
    import spell_client
    pes = [dict(classId=int(r["ClassID"]), level=int(r["Level"]), critPerAgility=float(r["CritPerAgility"]),
                spellCritPerIntellect=float(r["SpellCritPerIntellect"]), baseMana=int(r["BaseMana"]))
           for r in spell_client.table(build, "PlayerExpectedStat") if int(r["Level"]) <= 60 and r["ContentSetID"] == "0"]
    (DATA / "player_expected_stat.json").write_text(json.dumps(
        {"source": f"https://wago.tools/db2/PlayerExpectedStat/csv?build={build}", "rows": pes}, indent=0))


def go_class(c):
    return f"proto.Class_Class{CLASSES[c]}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--build", default=(REPO / "assets/db_inputs/forever_client_build.txt").read_text().strip())
    a = ap.parse_args()
    if a.refresh:
        refresh(a.build)
    cls = json.loads((DATA / "player_class_stats.json").read_text())["rows"]
    pes = json.loads((DATA / "player_expected_stat.json").read_text())["rows"]
    races = json.loads((DATA / "forever_race_starting_stats.json").read_text())
    by = {(r["classId"], r["level"]): r for r in cls}
    crit = {(r["classId"], r["level"]): r for r in pes}
    out = ["// Code generated by tools/forever_levels/generate_base_stats.py. DO NOT EDIT.", "", "package core", "",
           "import (", '\t"github.com/wowsims/classic/sim/core/proto"', '\t"github.com/wowsims/classic/sim/core/stats"', ")", "",
           "// Base health, mana and primary stats per class and level (index = level, 1-60), before race offsets.",
           "var classBaseStatsByLevel = map[proto.Class][61]stats.Stats{"]
    for c in CLASSES:
        out.append(f"\t{go_class(c)}: {{")
        out.append("\t\t{},")
        for lvl in range(1, 61):
            r = by[(c, lvl)]
            out.append(f"\t\t{{stats.Health: {r['health']}, stats.Mana: {r['mana']}, stats.Strength: {r['strength']}, stats.Agility: {r['agility']}, "
                       f"stats.Stamina: {r['stamina']}, stats.Intellect: {r['intellect']}, stats.Spirit: {r['spirit']}}}, // {lvl}")
        out.append("\t},")
    out += ["}", "", "// Melee crit chance (percent) per Agility point, client PlayerExpectedStat, per class and level.",
            "var critPerAgiByLevel = map[proto.Class][61]float64{"]
    for c in CLASSES:
        vals = ", ".join(f"{100 * crit[(c, lvl)]['critPerAgility']:.6g}" for lvl in range(1, 61))
        out.append(f"\t{go_class(c)}: {{0, {vals}}},")
    out += ["}", "", "// Spell crit chance (percent) per Intellect point, client PlayerExpectedStat, per class and level.",
            "var spellCritPerIntByLevel = map[proto.Class][61]float64{"]
    for c in CLASSES:
        vals = ", ".join(f"{100 * crit[(c, lvl)]['spellCritPerIntellect']:.6g}" for lvl in range(1, 61))
        out.append(f"\t{go_class(c)}: {{0, {vals}}},")
    out += ["}", "", f"// Forever level-1 race stats relative to Human ({races['source']}).", "var foreverRaceStartOffsets = map[proto.Race]stats.Stats{"]
    human = races["races"]["Human"]
    for name, v in races["races"].items():
        diff = {k: v[k] - human[k] for k in ("strength", "agility", "stamina", "intellect", "spirit")}
        body = ", ".join(f"stats.{k.capitalize()}: {d}" for k, d in diff.items() if d)
        out.append(f"\tproto.Race_Race{races['proto'][name]}: {{{body}}},")
    out += ["}", ""]
    OUT.write_text("\n".join(out))
    gofmt = pathlib.Path.home() / ".local/share/go/bin/gofmt"
    subprocess.run([str(gofmt) if gofmt.exists() else "gofmt", "-w", str(OUT)], check=False)
    print("wrote", OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
