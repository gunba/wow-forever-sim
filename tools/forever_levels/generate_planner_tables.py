#!/usr/bin/env python3
"""Tables the rotation planner's command-line binary embeds, so it can build a character without the network:

- sim/planner/expected_generated.go: creature health, auto-attack DPS and armor by level (client ExpectedStat).
- sim/planner/items.json.gz: item stats for gear lookups. From Wowhead's Forever gear planner snapshot
  (assets/db_inputs/wowhead_forever_gearplanner.txt), with weapons missing there filled in from the client's
  ItemSparse and ItemDamage tables (damage = table DPS for the item level and quality x speed, spread by DmgVariance).

    python3 tools/forever_levels/generate_planner_tables.py [--build 1.60.1.70374]
"""
import argparse, gzip, json, pathlib, re, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools/data_watch"))
import spell_client  # noqa: E402

PLANNER = REPO / "assets/db_inputs/wowhead_forever_gearplanner.txt"
STAT_KEYS = {"str": 0, "agi": 1, "sta": 2, "int": 3, "spi": 4, "atkpwr": 17, "hitrtng": 18, "critstrkrtng": 19, "exprtng": 22,
             "armor": 26, "defrtng": 28, "blockrtng": 29, "dodgertng": 31, "parryrtng": 32, "armorbonus": 40}
# ItemModType -> simulator stat index, for random suffix bonuses and client items.
MOD_TYPE = {3: 1, 4: 0, 5: 3, 6: 4, 7: 2, 12: 28, 13: 31, 14: 32, 15: 29, 31: 18, 32: 19, 38: 17, 37: 22}


def planner_items():
    s = PLANNER.read_text()
    start = 'setPageData("wow.gearPlanner.classicplus.item", '
    i = s.index(start) + len(start)
    txt = s[i:]
    end = txt.index("});") + 1
    return json.loads(re.sub(r",\s*}", "}", txt[:end]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="1.60.1.70374")
    a = ap.parse_args()

    es = [r for r in spell_client.table(a.build, "ExpectedStat") if r["ExpansionID"] == "-2" and r["ContentSetID"] == "0"]
    by = {int(r["Lvl"]): r for r in es}
    out = ["// Code generated by tools/forever_levels/generate_planner_tables.py. DO NOT EDIT.", f"// Client ExpectedStat, build {a.build}.", "",
           "package planner", "", "type expectedCreature struct{ health, autoAttackDPS, armor, armorConstant float64 }", "",
           "var expectedCreatures = [...]expectedCreature{", "\t{},"]
    for lvl in range(1, 64):
        r = by[lvl]
        out.append(f"\t{{{r['CreatureHealth']}, {float(r['CreatureAutoAttackDps']):.3f}, {r['CreatureArmor']}, {r['ArmorConstant']}}}, // {lvl}")
    out += ["}", ""]
    p = REPO / "sim/planner/expected_generated.go"
    p.write_text("\n".join(out))
    gofmt = pathlib.Path.home() / ".local/share/go/bin/gofmt"
    subprocess.run([str(gofmt) if gofmt.exists() else "gofmt", "-w", str(p)], check=False)

    items = {}
    for k, it in planner_items().items():
        st = it.get("stats", {})
        rec = {"c": it.get("class"), "s": it.get("subclass"), "inv": it.get("inventoryType"), "il": it.get("itemLevel")}
        stats = {str(idx): st[key] for key, idx in STAT_KEYS.items() if st.get(key)}
        if stats:
            rec["st"] = stats
        if st.get("mlespeed"):
            rec["w"] = [st.get("mledmgmin", 0), st.get("mledmgmax", 0), st["mlespeed"]]
        elif st.get("rgdspeed"):
            rec["r"] = [st.get("rgddmgmin", 0), st.get("rgddmgmax", 0), st["rgdspeed"]]
        if it.get("class") in (2, 4):
            items[int(k)] = rec
    # Client fill-in for weapons Wowhead lacks.
    sparse = {int(r["ID"]): r for r in spell_client.table(a.build, "ItemSparse")}
    base = {int(r["ID"]): r for r in spell_client.table(a.build, "Item")}
    d1 = {int(r["ItemLevel"]): r for r in spell_client.table(a.build, "ItemDamageOneHand")}
    d2 = {int(r["ItemLevel"]): r for r in spell_client.table(a.build, "ItemDamageTwoHand")}
    added = 0
    for iid, s in sparse.items():
        if iid in items or iid not in base or base[iid]["ClassID"] != "2":
            continue
        inv, il, q, delay = int(base[iid]["InventoryType"]), int(s["ItemLevel"]), int(s["OverallQualityID"]), int(s["ItemDelay"])
        table = d2 if inv == 17 else d1
        if delay <= 0 or il not in table or inv not in (13, 17, 21, 22):
            continue
        dps = float(table[il][f"Quality_{q}"])
        avg, var = dps * delay / 1000, float(s["DmgVariance"] or 0)
        items[iid] = {"c": 2, "s": int(base[iid]["SubclassID"]), "inv": inv, "il": il, "client": 1,
                      "w": [round(avg * (1 - var / 2)), round(avg * (1 + var / 2)), delay / 1000]}
        added += 1
    # Then the Classic Era item records already in the repository (assets/db_inputs/wago_db2_items.csv).
    import csv
    era = 0
    with open(REPO / "assets/db_inputs/wago_db2_items.csv", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            iid = int(r["ID"])
            if iid in items:
                continue
            inv = int(r["InventoryType"] or 0)
            rec = {"inv": inv, "il": int(r["ItemLevel"] or 0), "q": int(r["OverallQualityID"] or 0), "era": 1}
            delay = int(r["ItemDelay"] or 0)
            if delay > 0 and float(r["MaxDamage_0"] or 0) > 0:
                rec["c"] = 2
                rec["w"] = [float(r["MinDamage_0"]), float(r["MaxDamage_0"]), delay / 1000]
            else:
                rec["c"] = 4
            st = {}
            for k in range(10):
                t, v = int(r[f"StatModifier_bonusStat_{k}"] or -1), int(r[f"StatModifier_bonusAmount_{k}"] or 0)
                if t in MOD_TYPE and v:
                    st[str(MOD_TYPE[t])] = st.get(str(MOD_TYPE[t]), 0) + v
            if st:
                rec["st"] = st
            if iid in base:
                rec["c"], rec["s"] = int(base[iid]["ClassID"]), int(base[iid]["SubclassID"])
            if inv in range(1, 29):
                items[iid] = rec
                era += 1
    print("era fill-ins", era)
    # Random suffix bonus lists: stat type and allocation (x 1/10000 of the item's budget).
    bonus = {}
    for r in spell_client.table(a.build, "ItemBonus"):
        if r["Type"] == "2" and int(r["Value_0"]) in MOD_TYPE:
            bonus.setdefault(int(r["ParentItemBonusListID"]), []).append([MOD_TYPE[int(r["Value_0"])], int(r["Value_1"])])
    rpp = {int(r["ID"]): {q: [float(r[f"{q}_{i}"]) for i in range(5)] for q in ("Good", "Superior", "Epic")}
           for r in spell_client.table(a.build, "RandPropPoints")}
    for iid, rec in items.items():
        s = sparse.get(iid)
        if s:
            rec["q"] = int(s["OverallQualityID"])
    data = {"items": items, "bonus": bonus, "randProp": rpp, "build": a.build,
            "source": "Wowhead Forever gear planner snapshot plus client ItemSparse/ItemDamage/ItemBonus/RandPropPoints"}
    with gzip.open(REPO / "sim/planner/items.json.gz", "wt") as f:
        json.dump(data, f, separators=(",", ":"))
    print("items", len(items), "client fill-ins", added, "bonus lists", len(bonus))


if __name__ == "__main__":
    main()
