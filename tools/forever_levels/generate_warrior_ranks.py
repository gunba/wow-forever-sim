#!/usr/bin/env python3
"""Every rank of every trained Warrior ability, from the client spell tables, written to
sim/warrior/ranks/ranks_generated.go.

    python3 tools/forever_levels/generate_warrior_ranks.py [--build 1.60.1.70374]

The client gives each rank's learn level, rage cost, cooldown, duration and effect base points (damage, armor, attack
power, threat). Server-side numbers the client lacks (attack power coefficients, most flat threat) live beside this
table in sim/warrior/ranks/server.go.
"""
import argparse, json, pathlib, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools/data_watch"))
import spell_client  # noqa: E402

OUT = REPO / "sim/warrior/ranks/ranks_generated.go"
# Ability name -> Go identifier. Talent abilities are included: their higher ranks are trained.
ABILITIES = {
    "Battle Shout": "BattleShout", "Bloodrage": "Bloodrage", "Bloodthirst": "Bloodthirst", "Berserker Rage": "BerserkerRage",
    "Challenging Shout": "ChallengingShout", "Charge": "Charge", "Cleave": "Cleave", "Concussion Blow": "ConcussionBlow",
    "Death Wish": "DeathWish", "Demoralizing Shout": "DemoralizingShout", "Disarm": "Disarm", "Execute": "Execute",
    "Hamstring": "Hamstring", "Heroic Strike": "HeroicStrike", "Intercept": "Intercept", "Intimidating Shout": "IntimidatingShout",
    "Mocking Blow": "MockingBlow", "Mortal Strike": "MortalStrike", "Overpower": "Overpower", "Piercing Howl": "PiercingHowl",
    "Pummel": "Pummel", "Recklessness": "Recklessness", "Rend": "Rend", "Retaliation": "Retaliation", "Revenge": "Revenge",
    "Shield Bash": "ShieldBash", "Shield Block": "ShieldBlock", "Shield Slam": "ShieldSlam", "Shield Wall": "ShieldWall",
    "Slam": "Slam", "Spearing Strike": "SpearingStrike", "Sunder Armor": "SunderArmor", "Sweeping Strikes": "SweepingStrikes",
    "Taunt": "Taunt", "Thunder Clap": "ThunderClap", "Victory Rush": "VictoryRush", "Whirlwind": "Whirlwind",
    "Battle Stance": "BattleStance", "Defensive Stance": "DefensiveStance", "Berserker Stance": "BerserkerStance",
    "Last Stand": "LastStand",
}
# Records that share an ability's name but are not its trained ranks (talent passives, rune leftovers, effect spells).
SKIP = {20647, 12723, 12976}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=(REPO / "assets/db_inputs/forever_client_build.txt").read_text().strip())
    a = ap.parse_args()
    c = spell_client.Client(a.build)
    ranks = {}
    for sid in c.learned("warrior"):
        s = c.spell(sid)
        if not s or s["name"] not in ABILITIES or sid in SKIP:
            continue
        ranks.setdefault(s["name"], []).append(s)
    lines = ["// Code generated by tools/forever_levels/generate_warrior_ranks.py. DO NOT EDIT.",
             f"// Client build {a.build}.", "", "package ranks", "", "var generated = map[Ability][]Rank{"]
    for name in sorted(ranks, key=lambda n: ABILITIES[n]):
        lines.append(f"\t{ABILITIES[name]}: {{")
        for i, s in enumerate(sorted(ranks[name], key=lambda s: (s["level"], s["id"])), 1):
            cost = sum(x["flat"] for x in s["cost"] if x["power"] == "rage") / 10
            effs = ", ".join(
                f"{{Effect: {e['effect']}, Aura: {e['aura']}, Low: {e['low']}, High: {e['high']}, Misc: {e['miscValue']}, PeriodMs: {e['periodMs']}, "
                f"Trigger: {e['triggerSpell']}, APCoefficient: {e['apCoefficient']}}}" for e in s["effects"])
            lines.append(f"\t\t{{ID: {s['id']}, Rank: {i}, Level: {max(1, int(s['level']))}, Cost: {cost:g}, CooldownMs: {int(s['cooldownMs'])}, "
                         f"GCDMs: {int(s['gcdMs'])}, DurationMs: {int(s['durationMs'])}, Effects: []Effect{{{effs}}}}},")
        lines.append("\t},")
    lines += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    gofmt = pathlib.Path.home() / ".local/share/go/bin/gofmt"
    subprocess.run([str(gofmt) if gofmt.exists() else "gofmt", "-w", str(OUT)], check=False)
    print("wrote", OUT.relative_to(REPO), sum(len(v) for v in ranks.values()), "ranks of", len(ranks), "abilities")


if __name__ == "__main__":
    main()
